def _truth(L: dict) -> dict:
    diagnoses = [{"code": L["main"], "status": L["main_status"]}]
    diagnoses += [{"code": c, "status": "confirmed"} for c in L["comorbid"]]
    meds = [{"mnn": m["mnn"], "dose_mg": m["dose_mg"], "status": "current"} for m in L["current"]]
    meds += [{"mnn": m["mnn"], "dose_mg": m["dose_mg"], "status": "cancelled"} for m in L["cancelled"]]

    safety = {k: None for k in SAFETY_KEYS}
    for key, p in L["plan"].items():
        if p in ("pos", "pos_dx"):
            safety[key] = True
        elif p in ("neg", "neg_dx"):
            safety[key] = False
    # МАО: действующий → True; отменён — по сроку, если он виден из текста
    maoi = None
    if L["maoi_neg"]:
        maoi = False
    for m in L["current"]:
        if m["mnn"] in MAOIS:
            maoi = True
    for m in L["cancelled"]:
        if m["mnn"] in MAOIS:
            known = m["timing"] == "rel" or (m["timing"] == "abs" and L["has_date"])
            maoi = (m["days"] < 14) if known else None
    safety["maoi_within_2_weeks"] = maoi
    safety["hypersensitivity_aviandr"] = {"pos": True, "neg": False}.get(L["hyp"])
    allergies = None if L["allergies"] is None else list(L["allergies"])
    return {"diagnoses": diagnoses, "medications": meds, "allergies": allergies, "safety": safety}


