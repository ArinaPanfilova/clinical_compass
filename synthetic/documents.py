def _plural(n: int, forms: tuple[str, str, str]) -> str:
    n = abs(n) % 100
    if 11 <= n <= 14:
        return forms[2]
    return forms[{1: 0, 2: 1, 3: 1, 4: 1}.get(n % 10, 2)]


def _fmt_dose(d: float) -> str:
    return (f"{d:g}").replace(".", ",")


def _genitive(word: str) -> str:
    return word + "а" if word[-1].lower() not in "аеёиоуыэюяй" else word


def _sent(s: str) -> str:
    s = s.strip()
    if not s:
        return s
    s = s[0].upper() + s[1:]
    return s if s[-1] in ".!?" else s + "."


def _fill(tpl: str, nums: dict, **kw) -> str:
    return tpl.format(**nums, **kw)


