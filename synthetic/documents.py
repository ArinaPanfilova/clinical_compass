def _all_strings(obj):
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from _all_strings(v)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            yield from _all_strings(v)


def validate_pool(pool: dict) -> list[str]:
    """Структура пула совпадает с DEV_POOL: те же ключи, непустые списки там, где они непусты в dev.

    Возвращает список проблем (пустой — пул пригоден)."""
    problems = []

    def walk(ref, got, path):
        if isinstance(ref, dict):
            if not isinstance(got, dict):
                problems.append(f"{path}: ожидается dict")
                return
            for k in ref:
                if k not in got:
                    problems.append(f"{path}.{k}: нет ключа")
                else:
                    walk(ref[k], got[k], f"{path}.{k}")
            for k in got:
                if k not in ref:
                    problems.append(f"{path}.{k}: лишний ключ")
        elif isinstance(ref, list):
            if not isinstance(got, list):
                problems.append(f"{path}: ожидается list")
            elif ref and not got:
                problems.append(f"{path}: пустой список")
            elif ref and isinstance(ref[0], dict):
                for i, item in enumerate(got):
                    if not isinstance(item, dict) or set(item) != set(ref[0]):
                        problems.append(f"{path}[{i}]: ожидаются ключи {sorted(ref[0])}")

    walk(DEV_POOL, pool, "pool")
    return problems


