class _Renderer:
    def __init__(self, L: dict, pool: dict, phr: random.Random):
        self.L, self.P, self.r = L, pool, phr
        self.nums = L["nums"]

    def pick(self, key_or_list):
        lst = self.P[key_or_list] if isinstance(key_or_list, str) else key_or_list
        return self.r.choice(lst)

    def f(self, tpl: str, **kw) -> str:
        return _fill(tpl, self.nums, **kw)

    # Диагнозы
    def main_dx(self, kind: str) -> str:
        L = self.L
        names = self.P["psy_names"][L["main"]]
        name = self.pick(names["short"] if kind == "short" else names["full"])
        if L["main_show"] == "code":
            return L["main"]
        if L["main_show"] == "name":
            return name
        return self.f(self.pick("dx_with_code"), name=name, code=L["main"])

    def comorbid_items(self, kind: str) -> list[str]:
        out = []
        for code, shown in zip(self.L["comorbid"], self.L["comorbid_codes_shown"]):
            name = self.f(self.pick(self.P["somatic_names"][code][kind]))
            out.append(self.f(self.pick("dx_with_code"), name=name, code=code) if shown else name)
        return out

    def main_line(self, tpl_letter: str, kind: str) -> str:
        status = self.L["main_status"]
        return self.f(self.pick(f"main_{tpl_letter}_{status}"), dx=self.main_dx(kind))

    # Безопасность
    def safety_phrases(self, short: bool) -> list[str]:
        out = []
        for key, p in self.L["plan"].items():
            if p not in ("pos", "neg"):
                continue
            entry = self.P["safety"][key]
            lst = entry[p + "_short"] if short and entry[p + "_short"] else entry[p]
            out.append(self.f(self.pick(lst)))
        if self.L["maoi_neg"]:
            e = self.P["safety"]["maoi_within_2_weeks"]
            out.append(self.f(self.pick(e["neg_short"] if short else e["neg"])))
        if self.L["hyp"] == "neg":
            e = self.P["safety"]["hypersensitivity_aviandr"]
            out.append(self.f(self.pick(e["neg_short"] if short else e["neg"])))
        return out

    def family(self) -> str | None:
        if not self.L["family"]:
            return None
        return self.f(self.pick("family"), fdx=self.pick(self.P["family_dx"][self.L["family"]]),
                      rel=self.pick("relatives"))

    def hypothetical(self) -> str | None:
        h = self.L["hypothetical"]
        return self.f(self.pick(self.P["hypothetical"][h])) if h else None

    # Препараты
    def drug(self, mnn: str) -> str:
        return self.pick(self.P["drug_names"][mnn])

    def when(self, m: dict) -> str:
        t = m.get("timing", "none")
        if t == "abs":
            d = self.L["doc_date"] - timedelta(days=m["days"])
            return " " + (d.strftime("%d.%m") if self.r.random() < 0.6 else d.strftime("%d.%m.%Y"))
        if t == "rel":
            n = m["days"]
            forms = self.P["ago"].get(str(n)) or self.P["ago"]["default"]
            return " " + self.f(self.pick(forms), n=n, days_word=_plural(n, ("день", "дня", "дней")))
        return ""

    def start(self, m: dict) -> str:
        return (self.L["doc_date"] - timedelta(days=m["start_days"])).strftime("%d.%m.%Y")

    def med(self, m: dict, status: str, letter: str) -> str:
        key = f"med_{status}_{letter}"
        if m["dose_mg"] is None:
            key += "_nodose"
        drug = self.drug(m["mnn"])
        took = "принимала" if self.L["sex"] == "Ж" else "принимал"
        sched = self.pick("sched_short" if letter == "C" else "sched")
        return self.f(self.pick(key), drug=drug, dose=_fmt_dose(m["dose_mg"]) if m["dose_mg"] else "",
                      sched=sched, when=self.when(m) if status == "cancelled" else "",
                      reason=self.pick("reasons"), took=took,
                      start=self.start(m) if status == "current" else "")

    def continue_recs(self, letter: str) -> list[str]:
        out = []
        for m in self.L["current"]:
            if self.r.random() < 0.5:
                drug = self.drug(m["mnn"])
                out.append(self.f(self.pick(f"continue_rec_{letter}"), drug=drug, drug_gen=_genitive(drug),
                                  dose=_fmt_dose(m["dose_mg"]), sched=self.pick("sched")))
        return out

    # Аллергии
    def allergy(self, letter: str) -> str | None:
        al = self.L["allergies"]
        if al is None:
            return None
        if not al:
            return self.f(self.pick(f"allergy_neg_{letter}"))
        forms = [self.pick(self.P["allergens"][a]) for a in al]
        joiner = self.r.choice((", ", " и "))
        return self.f(self.pick(f"allergy_pos_{letter}"),
                      nom=joiner.join(x["nom"] for x in forms), gen=joiner.join(x["gen"] for x in forms),
                      acc=joiner.join(x["acc"] for x in forms), reaction=self.pick("reactions"))

    def patient(self, short: bool = False) -> str:
        L = self.L
        if short:
            return f"{'Пац-ка' if L['sex'] == 'Ж' else 'Пац.'} {L['initial']}., {L['age']} л."
        word = _plural(L["age"], ("год", "года", "лет"))
        return f"{'Пациентка' if L['sex'] == 'Ж' else 'Пациент'} {L['initial']}., {L['age']} {word}"

    # Шаблоны
    def render_A(self) -> str:
        L, P = self.L, self.P
        head = [self.pick("title_A"), self.patient()]
        if L["has_date"]:
            head.append(self.f(self.pick("date_A"), date=_fmt_date(L["doc_date"], "full")))
        H = P["a_headers"]
        sections = []
        dx_lines = [self.main_line("A", "full")]
        if L["comorbid"]:
            sep = self.r.choice(("; ", ", "))
            dx_lines.append(self.f(self.pick("comorbid_A"), list=sep.join(self.comorbid_items("full"))))
        elif self.r.random() < 0.5:
            dx_lines.append(self.pick("comorbid_A_none"))
        sections.append([self.pick(H["diagnosis"])] + dx_lines)

        anam = self.safety_phrases(short=False)
        fam = self.family()
        if fam:
            anam.append(fam)
        self.r.shuffle(anam)
        sections.append([self.pick(H["anamnesis"]),
                         " ".join(_sent(s) for s in anam) if anam else self.pick("anamnesis_empty")])

        al = self.allergy("A")
        if al:
            sections.append([self.pick(H["allergy"]), _sent(al)])

        meds = [self.med(m, "current", "A") for m in L["current"]]
        meds += [self.med(m, "cancelled", "A") for m in L["cancelled"]]
        if L["somatic_meds"]:
            meds.insert(self.r.randint(0, len(meds)), self.pick("somatic_meds"))
        sections.append([self.pick(H["treatment"])] + ([_sent(x) for x in meds] or [_sent(self.pick("no_meds_A"))]))

        recs = self.continue_recs("A")
        hyp = self.hypothetical()
        if hyp:
            recs.append(hyp)
        recs.append(self.pick("recs_generic"))
        self.r.shuffle(recs)
        sections.append([self.pick(H["recommendations"])] + [_sent(x) for x in recs])

        self.r.shuffle(sections)
        return "\n".join(head) + "\n\n" + "\n\n".join("\n".join(s) for s in sections) + "\n"

    def render_B(self) -> str:
        L = self.L
        title = self.pick("title_B")
        if L["has_date"]:
            title += " от " + _fmt_date(L["doc_date"], self.r.choice(("full", "long")))
        lines = [_sent(title), f"{self.patient()}. Жалобы на {self.pick('complaints')}."]
        body = []
        if L["comorbid"]:
            if self.r.random() < 0.5:
                body.append(self.f(self.pick("comorbid_B_instr"), list=" и ".join(self.comorbid_items("instr"))))
            else:
                body.append(self.f(self.pick("comorbid_B_full"), list=", ".join(self.comorbid_items("full"))))
        body += [_sent(s) for s in self.safety_phrases(short=False)]
        fam = self.family()
        if fam:
            body.append(_sent(fam))
        body += [self.med(m, "current", "B") for m in L["current"]]
        body += [self.med(m, "cancelled", "B") for m in L["cancelled"]]
        if L["somatic_meds"]:
            sm = self.pick("somatic_meds")
            body.append("Также принимает " + sm[0].lower() + sm[1:] + ".")
        al = self.allergy("B")
        if al:
            body.append(_sent(al))
        self.r.shuffle(body)
        main = self.main_line("B", "full")
        if self.r.random() < 0.5:
            body.insert(0, main)
        else:
            body.append(main)
        lines.append(" ".join(body))
        recs = self.continue_recs("B")
        hyp = self.hypothetical()
        if hyp:
            recs.append(_sent(hyp))
        if recs:
            lines.append(" ".join(recs))
        return "\n".join(lines) + "\n"

    def render_C(self) -> str:
        L = self.L
        title = self.pick("title_C")
        if L["has_date"]:
            title += " " + _fmt_date(L["doc_date"], "short")
        lines = [title, self.patient(short=True), self.main_line("C", "short")]
        if L["comorbid"]:
            lines.append(self.f(self.pick("comorbid_C"), list=", ".join(self.comorbid_items("short"))) + ".")
        items = [self.med(m, "current", "C") for m in L["current"]]
        items += [self.med(m, "cancelled", "C") for m in L["cancelled"]]
        if items:
            lines.append(self.f(self.pick("therapy_C"), list="; ".join(items)) + ".")
        al = self.allergy("C")
        if al:
            lines.append(_sent(al))
        sp = self.safety_phrases(short=True)
        if sp:
            lines.append(" ".join(_sent(s) for s in sp))
        fam = self.family()
        if fam:
            lines.append(_sent(fam))
        return "\n".join(lines) + "\n"


def generate_documents(n: int, seed: int, pool: str = "dev") -> list[dict]:
    """n документов с эталоном. Содержание (эталон) зависит только от seed, формулировки — от пула.

    Элемент: {"doc_id", "template", "text", "truth"}; truth — см. модульную документацию."""
    if pool not in POOLS:
        raise ValueError(f"Неизвестный пул {pool!r}; есть: {sorted(POOLS)}")
    P = POOLS[pool]
    lat = random.Random(f"lat:{seed}")
    phr = random.Random(f"phr:{pool}:{seed}")
    docs = []
    for i in range(n):
        L = _latent(lat)
        R = _Renderer(L, P, phr)
        text = {"А": R.render_A, "Б": R.render_B, "В": R.render_C}[L["template"]]()
        docs.append({"doc_id": f"{pool}-{seed}-{i:04d}", "template": L["template"], "text": text,
                     "truth": _truth(L)})
    return docs


